package cookbookofbabel.minecraft.datagen;

import com.google.gson.GsonBuilder;
import com.google.gson.JsonArray;
import com.google.gson.JsonObject;
import cookbookofbabel.minecraft.CookbookOfBabel;
import cookbookofbabel.minecraft.dataset.Ingredient;
import cookbookofbabel.minecraft.datagen.plan.Quantize;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Locale;
import java.util.Set;
import java.util.TreeSet;
import java.util.concurrent.CompletableFuture;
import java.util.stream.Collectors;
import java.util.stream.Stream;
import net.minecraft.data.CachedOutput;
import net.minecraft.data.DataProvider;
import net.minecraftforge.fml.ModList;
import net.minecraftforge.registries.ForgeRegistries;

/**
 * What datagen made of the dataset, for whoever curates it: {@code coverage.md}, committed, and
 * {@code candidates.json}, a starting point for new mappings. Runs after the recipes.
 */
final class Reports implements DataProvider {
    private final DatagenContext context;

    Reports(DatagenContext context) {
        this.context = context;
    }

    @Override
    public CompletableFuture<?> run(CachedOutput output) {
        try {
            var leaves = unmappedLeaves();
            Files.writeString(context.coverageFile, coverage(leaves), StandardCharsets.UTF_8);
            Files.createDirectories(context.candidatesFile.getParent());
            Files.writeString(context.candidatesFile, candidates(leaves), StandardCharsets.UTF_8);
            return CompletableFuture.completedFuture(null);
        } catch (IOException e) {
            return CompletableFuture.failedFuture(e);
        }
    }

    /** Ingredients no step makes and no mod provides: nothing in the game can produce them. */
    private List<Ingredient> unmappedLeaves() {
        var made = context.producedSomewhere();
        return context.dataset.ingredients().stream()
                .filter(i -> !made.contains(i.id()))
                .filter(i -> context.mappings.stream().noneMatch(m -> m.entry(i.id()).isPresent()))
                .filter(i -> context.recipes().stream().anyMatch(r -> cookbookofbabel.minecraft.datagen.plan.Recipes.consumes(r, i.id())))
                .toList();
    }

    private String coverage(List<Ingredient> leaves) {
        var out = new StringBuilder();
        out.append("# Coverage\n\n");
        out.append("Generated by `./gradlew runData` from the dataset export; do not edit.\n\n");
        out.append("Substance colours are derived from their IDs until the dataset records colours.\n\n");

        out.append("## Unmapped leaves\n\n");
        out.append("Used by some step, made by none, and provided by no mapped mod, so nothing in the game produces them. ");
        out.append("`build/babel/candidates.json` lists items and tags that might.\n\n");
        leaves.forEach(i -> out.append("- `").append(i.id()).append("` (").append(i.label()).append(")\n"));
        if (leaves.isEmpty()) {
            out.append("None.\n");
        }

        out.append("\n## Elided steps\n\n");
        out.append("Steps that should happen over time, skipped until the mod has a time mechanic.\n\n");
        for (var e : context.elision.elided()) {
            var how = switch (e.rewire()) {
                case PRODUCERS_MAKE_OUTPUT -> "steps that made `" + e.input() + "` make `" + e.output() + "`";
                case CONSUMERS_TAKE_INPUT -> "steps that took `" + e.output() + "` take `" + e.input() + "`";
            };
            out.append("- `").append(e.recipe()).append("`: ").append(how).append('\n');
        }

        out.append("\n## Steps\n\n");
        out.append("Rounding error is the largest relative error of any non-negligible amount; above ")
                .append(percent(Quantize.TOLERANCE)).append(" it is marked ⚠. *Estimated*: a density or piece mass was assumed.\n");
        for (var step : context.coverage.steps()) {
            out.append("\n### `").append(step.recipe()).append("` (").append(step.technique()).append(")\n\n");
            step.note().ifPresent(n -> out.append("No routes: ").append(n).append(".\n"));
            for (var variant : step.variants()) {
                if (step.variants().size() > 1) {
                    out.append("- `").append(variant.path()).append("`\n");
                }
                var indent = step.variants().size() > 1 ? "  " : "";
                variant.addedMedium().ifPresent(m -> out.append(indent).append("- adds `").append(m)
                        .append("`: the step uses it up but doesn't list it (a dataset gap)\n"));
                for (var route : variant.routes()) {
                    out.append(indent).append("- ").append(Coverage.routeName(route.route())).append(": ");
                    if (route.outcome() instanceof Coverage.Emitted e) {
                        out.append(e.recipes()).append(e.recipes() == 1 ? " recipe" : " recipes")
                                .append(", rounding ").append(percent(e.maxError()))
                                .append(e.maxError() > Quantize.TOLERANCE ? " ⚠" : "")
                                .append(e.estimated() ? ", estimated" : "");
                        if (!e.dropped().isEmpty()) {
                            out.append(", drops ").append(e.dropped().stream().map(d -> "`" + d + "`").collect(Collectors.joining(", ")));
                        }
                    } else {
                        out.append("none, ").append(((Coverage.Rejected) route.outcome()).reason());
                    }
                    out.append('\n');
                }
            }
        }

        out.append("\n## Deferred\n\n");
        Stream.of(
                        "Passive, time-based changes (cool, chill, age, ferment, spoil and the rest) need a time mechanic.",
                        "Water as a medium that boiling, simmering and steaming use up.",
                        "A real sieve for sifting-type strain steps.",
                        "Outputs that are one of several outcomes.")
                .forEach(line -> out.append("- ").append(line).append('\n'));
        return out.toString();
    }

    /** Other mods' items and tags whose IDs mention an unmapped leaf's ID, label or aliases. */
    private String candidates(List<Ingredient> leaves) throws IOException {
        var items = ForgeRegistries.ITEMS.getKeys().stream().map(Object::toString).sorted().toList();
        var tags = itemTags();
        var json = new JsonObject();
        for (var leaf : leaves) {
            var words = words(leaf);
            var entry = new JsonObject();
            entry.add("items", array(items.stream().filter(id -> matches(id, words))));
            entry.add("itemTags", array(tags.stream().filter(id -> matches(id, words))));
            json.add(leaf.id().value(), entry);
        }
        return new GsonBuilder().setPrettyPrinting().create().toJson(json) + "\n";
    }

    private static Set<String> words(Ingredient ingredient) {
        var words = new TreeSet<String>();
        words.add(ingredient.id().value());
        Stream.concat(Stream.of(ingredient.label()), ingredient.aliases().stream())
                .map(s -> s.toLowerCase(Locale.ROOT).replaceAll("[^a-z0-9]+", "_").replaceAll("^_|_$", ""))
                .filter(s -> !s.isEmpty())
                .forEach(words::add);
        return words;
    }

    private static boolean matches(String id, Set<String> words) {
        if (id.startsWith(CookbookOfBabel.ID + ":")) {
            return false;
        }
        var path = id.substring(id.indexOf(':') + 1);
        return words.stream().anyMatch(path::contains);
    }

    /** Tags aren't loaded during datagen, so read their files from every mod. */
    private static List<String> itemTags() throws IOException {
        var tags = new TreeSet<String>();
        for (var modFile : ModList.get().getModFiles()) {
            var data = modFile.getFile().findResource("data");
            if (!Files.isDirectory(data)) {
                continue;
            }
            try (var files = Files.walk(data)) {
                files.filter(p -> p.toString().endsWith(".json")).forEach(p -> tagId(data, p).ifPresent(tags::add));
            }
        }
        return new ArrayList<>(tags);
    }

    private static java.util.Optional<String> tagId(Path data, Path file) {
        var parts = data.relativize(file).toString().replace('\\', '/').split("/", 4);
        if (parts.length < 4 || !parts[1].equals("tags") || !parts[2].equals("items")) {
            return java.util.Optional.empty();
        }
        return java.util.Optional.of(parts[0] + ":" + parts[3].substring(0, parts[3].length() - ".json".length()));
    }

    private static JsonArray array(Stream<String> values) {
        var array = new JsonArray();
        values.forEach(array::add);
        return array;
    }

    private static String percent(double fraction) {
        return Math.round(fraction * 100) + "%";
    }

    @Override
    public String getName() {
        return "Coverage report";
    }
}
