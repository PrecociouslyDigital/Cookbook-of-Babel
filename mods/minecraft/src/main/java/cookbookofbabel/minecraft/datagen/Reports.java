/**
 * What datagen made of the dataset, for whoever curates it: {@code coverage.md}, committed, and
 * {@code candidates/<mod>.json}, proposed mappings. Runs after the recipes.
 */
final class Reports implements DataProvider {
    private final DatagenContext context;

    Reports(DatagenContext context) {
        this.context = context;
    }

    @Override
    public CompletableFuture<?> run(CachedOutput output) {
        try {
            Files.writeString(context.coverageFile, coverage(unmappedLeaves()), StandardCharsets.UTF_8);
            proposals();
            return CompletableFuture.completedFuture(null);
        } catch (IOException e) {
            return CompletableFuture.failedFuture(e);
        }
    }

    /**
     * Ingredients no step makes, no mod provides and the mod doesn't plant, nor anything that counts
     * as them: nothing in the game can produce them.
     */
    private List<Ingredient> unmappedLeaves() {
        var made = context.producedSomewhere();
        return context.dataset.ingredients().stream()
                .filter(i -> context.dataset.descendants(i.id()).stream().noneMatch(d -> made.contains(d)
                        || context.mappings.stream().anyMatch(m -> m.entry(d).isPresent())
                        || SpiceGardens.all().containsKey(d)))
                .filter(i -> context.recipes().stream().anyMatch(r -> cookbookofbabel.minecraft.datagen.plan.Recipes.consumes(r, i.id())))
                .toList();
    }

    private String coverage(List<Ingredient> leaves) {
        var out = new StringBuilder();
        out.append("# Coverage\n\n");
        out.append("Generated by `./gradlew runData` from the dataset export; do not edit.\n\n");
        out.append("Substance colours are derived from their IDs until the dataset records colours.\n\n");

        out.append("## Techniques\n\n");
        out.append("Steps of each technique: all of them, those with a recipe in at least one machine, and those written as a transition.\n\n");
        out.append("| Technique | Steps | With a recipe | As a transition |\n|---|---|---|---|\n");
        context.coverage.steps().stream()
                .collect(Collectors.groupingBy(Coverage.Step::technique, TreeMap::new, Collectors.toList()))
                .forEach((technique, steps) -> out.append("| ").append(technique)
                        .append(" | ").append(steps.size())
                        .append(" | ").append(steps.stream().filter(Coverage.Step::emitted).count())
                        .append(" | ").append(steps.stream().filter(Coverage.Step::kept).count())
                        .append(" |\n"));

        out.append("\n## Unmapped leaves\n\n");
        out.append("Used by some step, and neither they nor anything that counts as them is made by a step or provided by a mapped mod, so nothing in the game produces them. ");
        out.append("`build/babel/candidates/<mod>.json` proposes mappings for them and for anything else that a mod's items or fluids name.\n\n");
        leaves.forEach(i -> out.append("- `").append(i.id()).append("` (").append(i.label()).append(")\n"));
        if (leaves.isEmpty()) {
            out.append("None.\n");
        }

        out.append("\n## Planted spices\n\n");
        out.append("Spices no mapped mod grows, which the mod plants itself (`cookbook_of_babel/spice_gardens.json`), ");
        out.append("and the HarvestCraft 2 gardens their seeds drop from.\n\n");
        SpiceGardens.all().forEach((spice, gardens) -> out.append("- `").append(spice).append("` (")
                .append(context.dataset.ingredient(spice).label()).append("): ")
                .append(gardens.stream().map(Garden::getSerializedName).collect(Collectors.joining(", "))).append('\n'));

        out.append("\n## Merged ingredients\n\n");
        out.append("Preparations the dataset keeps apart but one machine here makes alike: each line is the ingredient kept, ");
        out.append("then those merged into it.\n\n");
        var mergedInto = new TreeMap<IngredientId, List<IngredientId>>();
        context.merging.merged().forEach((from, to) -> mergedInto.computeIfAbsent(to, k -> new ArrayList<>()).add(from));
        mergedInto.forEach((kept, merged) -> out.append("- `").append(kept).append("`: ")
                .append(merged.stream().map(m -> "`" + m + "`").collect(Collectors.joining(", "))).append('\n'));
        if (mergedInto.isEmpty()) {
            out.append("None.\n");
        }
        if (!context.merging.dropped().isEmpty()) {
            out.append("\nSteps that merging left the same as another, and so dropped:\n\n");
            context.merging.dropped().forEach(d -> out.append("- `").append(d.recipe()).append("`, like `").append(d.keptRecipe()).append("`\n"));
        }

        out.append("\n## Elided steps\n\n");
        out.append("Crafting steps that turn one ingredient into another and nothing more, which would be no-op crafts here: ");
        out.append("each line is the step, its input and output, then the ingredient they became.\n\n");
        context.eliding.elided().forEach(e -> out.append("- `").append(e.recipe()).append("`: `").append(e.input())
                .append("` → `").append(e.output()).append("`, now `").append(e.kept()).append("`\n"));
        if (context.eliding.elided().isEmpty()) {
            out.append("None.\n");
        }
        if (!context.eliding.dropped().isEmpty()) {
            out.append("\nSteps that eliding left the same as another, and so dropped:\n\n");
            context.eliding.dropped().forEach(d -> out.append("- `").append(d.recipe()).append("`, like `").append(d.keptRecipe()).append("`\n"));
        }

        out.append("\n## Supplanted items\n\n");
        out.append("Ingredients the mod's live recipes make as other mods' items, and every item mapped to each. ");
        out.append("In game those items lose every recipe but the mod's own: the item the mod makes is supplanted, the rest withdrawn. ");
        out.append("`withdrawn.json` lists further items withdrawn by hand.\n\n");
        var supplanted = context.coverage.supplanted();
        supplanted.forEach((ingredient, items) -> out.append("- `").append(ingredient).append("`: ")
                .append(Coverage.code(items.stream())).append('\n'));
        if (supplanted.isEmpty()) {
            out.append("None.\n");
        }

        transitions(out);

        out.append("\n## Steps\n\n");
        out.append("Rounding error is the largest relative error of any non-negligible amount; above ")
                .append(Coverage.percent(Quantize.TOLERANCE)).append(" it is marked ⚠. *Estimated*: a density or piece mass was assumed.\n");
        for (var step : context.coverage.steps()) {
            out.append("\n### `").append(step.recipe()).append("` (").append(step.technique()).append(")\n\n");
            step.note().ifPresent(n -> out.append("No routes: ").append(n).append(".\n"));
            step.transition().ifPresent(k -> out.append("- transition: ").append(k.live() ? "written" : unwritten(k)).append('\n'));
            for (var variant : step.variants()) {
                if (step.variants().size() > 1) {
                    out.append("- `").append(variant.path()).append("`\n");
                }
                var indent = step.variants().size() > 1 ? "  " : "";
                variant.addedMedium().ifPresent(m -> out.append(indent).append("- adds `").append(m)
                        .append("`: the step uses it up but doesn't list it (a dataset gap)\n"));
                for (var route : variant.routes()) {
                    out.append(indent).append("- ").append(Coverage.routeName(route.route())).append(": ")
                            .append(route.outcome().describe()).append('\n');
                }
            }
        }

        pruned(out);

        out.append("\n## Deferred\n\n");
        Stream.of(
                        "Water as a medium that boiling, simmering and steaming use up.",
                        "A real sieve for sifting-type strain steps.",
                        "Outputs that are one of several outcomes.")
                .forEach(line -> out.append("- ").append(line).append('\n'));
        return out.toString();
    }

    private void transitions(StringBuilder out) {
        out.append("\n## Transitions\n\n");
        out.append("Steps that happen to food while it is kept rather than in a machine: one ingredient becomes another after the duration, ");
        out.append("which holds at the reference temperature and q10 scales per 10 °C. One whose input the game can't make isn't written.\n\n");
        var kept = context.coverage.steps().stream().flatMap(s -> s.transition().stream()).toList();
        kept.forEach(k -> out.append("- `").append(k.transition().recipe()).append("`: ").append(describe(k)).append('\n'));
        if (kept.isEmpty()) {
            out.append("None.\n");
        }
    }

    private String describe(Coverage.Kept kept) {
        var t = kept.transition();
        var s = t.sensitivity();
        var bands = context.export.constants().tempBands();
        var out = new StringBuilder(t.kind().getSerializedName())
                .append(", `").append(t.input()).append("` → `").append(t.output()).append("`, ")
                .append(number(t.duration().qty())).append(' ').append(t.duration().unit())
                .append(" (").append(t.ticks()).append(" ticks) at ").append(number(s.refTempC())).append(" °C, ").append(bands.bandOf(s.refTempC()));
        if (s.q10() != 1) {
            out.append(", q10 ").append(number(s.q10()));
        }
        if (s.minTempC().isPresent() || s.maxTempC().isPresent()) {
            out.append(", only from ").append(s.minTempC().map(c -> number(c) + " °C").orElse("any"))
                    .append(" to ").append(s.maxTempC().map(c -> number(c) + " °C").orElse("any"));
        }
        if (!kept.live()) {
            out.append(", ").append(unwritten(kept));
        }
        return out.toString();
    }

    private static String unwritten(Coverage.Kept kept) {
        return "not written: the game can't make " + Coverage.code(kept.missing().stream().map(IngredientId::value));
    }

    private static String number(double x) {
        return x == Math.rint(x) ? Long.toString((long) x) : Double.toString(x);
    }

    private record PrunedRoute(String path, RouteKind route, Coverage.Pruned outcome) {}

    private void pruned(StringBuilder out) {
        var pruned = context.coverage.steps().stream()
                .flatMap(s -> s.variants().stream())
                .flatMap(v -> v.routes().stream().flatMap(r -> r.outcome() instanceof Coverage.Pruned p
                        ? Stream.of(new PrunedRoute(v.path(), r.route(), p))
                        : Stream.empty()))
                .toList();
        out.append("\n## Pruned\n\n");
        out.append("Routes written disabled (`forge:false`): the game can't make some of their inputs, nor anything that counts as them, ");
        out.append("starting from what no step makes and what other mods provide.\n\n");
        if (pruned.isEmpty()) {
            out.append("None.\n");
            return;
        }
        out.append("Inputs by how many pruned routes miss them:\n\n");
        pruned.stream()
                .flatMap(p -> p.outcome().missing().stream())
                .collect(Collectors.groupingBy(i -> i, TreeMap::new, Collectors.counting()))
                .entrySet().stream()
                .sorted(Map.Entry.<IngredientId, Long>comparingByValue().reversed())
                .forEach(e -> out.append("- `").append(e.getKey()).append("`: ").append(e.getValue()).append('\n'));
        out.append("\nEach pruned route, and what it misses:\n\n");
        pruned.forEach(p -> out.append("- `").append(p.path()).append("`, ").append(Coverage.routeName(p.route())).append(": ")
                .append(Coverage.code(p.outcome().missing().stream().map(IngredientId::value))).append('\n'));
    }

    /**
     * For each mod, the ingredients it doesn't map yet that one of its items or fluids names, in the
     * format of {@code mappings/<mod>.json}.
     */
    private void proposals() throws IOException {
        Files.createDirectories(context.candidatesDirectory);
        var names = englishNames();
        var items = ForgeRegistries.ITEMS.getKeys().stream()
                .map(id -> new Proposals.Named(id.toString(), names.firstOf("item." + lang(id), "block." + lang(id))))
                .toList();
        var fluids = ForgeRegistries.FLUIDS.getKeys().stream()
                .filter(id -> !id.getPath().startsWith("flowing_"))
                .map(id -> new Proposals.Named(id.toString(), names.firstOf("fluid_type." + lang(id), "fluid." + lang(id))))
                .toList();
        for (var mod : Mod.values()) {
            var mapped = context.mappings.stream().filter(m -> m.mod() == mod).flatMap(m -> m.entries().keySet().stream()).collect(Collectors.toSet());
            var unmapped = context.dataset.ingredients().stream().filter(i -> !mapped.contains(i.id())).toList();
            var itemMatches = Proposals.match(unmapped, items.stream().filter(i -> i.id().startsWith(mod.namespace + ":")).toList());
            var fluidMatches = Proposals.match(unmapped, fluids.stream().filter(f -> f.id().startsWith(mod.namespace + ":")).toList());
            var json = new JsonObject();
            for (var ingredient : unmapped) {
                var entry = new JsonObject();
                Optional.ofNullable(itemMatches.get(ingredient.id())).ifPresent(ids -> {
                    var array = new JsonArray();
                    ids.forEach(id -> {
                        var item = new JsonObject();
                        item.addProperty("id", id);
                        array.add(item);
                    });
                    entry.add("items", array);
                });
                Optional.ofNullable(fluidMatches.get(ingredient.id())).ifPresent(ids -> entry.add("fluids", array(ids.stream())));
                if (entry.size() > 0) {
                    json.add(ingredient.id().value(), entry);
                }
            }
            var file = context.candidatesDirectory.resolve(mod.id + ".json");
            Files.writeString(file, new GsonBuilder().setPrettyPrinting().create().toJson(json) + "\n", StandardCharsets.UTF_8);
        }
    }

    private static String lang(ResourceLocation id) {
        return id.getNamespace() + "." + id.getPath();
    }

    private record Lang(Map<String, String> entries) {
        Optional<String> firstOf(String... keys) {
            return Stream.of(keys).flatMap(k -> Optional.ofNullable(entries.get(k)).stream()).findFirst();
        }
    }

    /** Language files aren't loaded during datagen, so read every mod's English one. */
    private static Lang englishNames() throws IOException {
        var entries = new HashMap<String, String>();
        for (var modFile : ModList.get().getModFiles()) {
            var assets = modFile.getFile().findResource("assets");
            if (!Files.isDirectory(assets)) {
                continue;
            }
            try (var namespaces = Files.list(assets)) {
                for (var namespace : namespaces.toList()) {
                    var file = namespace.resolve("lang/en_us.json");
                    if (!Files.isRegularFile(file)) {
                        continue;
                    }
                    try {
                        JsonParser.parseString(Files.readString(file, StandardCharsets.UTF_8)).getAsJsonObject().entrySet().stream()
                                .filter(e -> e.getValue().isJsonPrimitive())
                                .forEach(e -> entries.putIfAbsent(e.getKey(), e.getValue().getAsString()));
                    } catch (RuntimeException e) {
                        // A mod's malformed language file only costs its names in the proposals.
                    }
                }
            }
        }
        return new Lang(entries);
    }

    private static JsonArray array(Stream<String> values) {
        var array = new JsonArray();
        values.forEach(array::add);
        return array;
    }

    @Override
    public String getName() {
        return "Coverage report";
    }
}
